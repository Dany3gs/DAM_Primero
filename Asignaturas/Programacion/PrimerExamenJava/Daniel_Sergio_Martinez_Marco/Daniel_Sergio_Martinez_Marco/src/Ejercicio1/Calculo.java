package Ejercicio1;

public class Calculo {

    public static double sumaDosNumeros(double numero1, double numero2){
        return numero1 + numero2;
    }

    public static double multiplicaDosNumeros(double numero1, double numero2){
        return numero1 * numero2;
    }
    public static double restaDosNumeros(double numero1, double numero2){
        return numero1 - numero2;
    }
    public static double divideDosNumeros(double numero1, double numero2){
        return numero1 / numero2;
    }
}
